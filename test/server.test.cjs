const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const request = require('supertest');
const sharp = require('sharp');
const { createApp } = require('../server.cjs');
const { hash } = require('../lib/security.cjs');
const { quoteInput } = require('../lib/quotes.cjs');
const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'ag-balloons-test-'));
const mailbox = [];
const app = createApp({ dataDir, test:true, adminEmail:'admin@example.com', sendMail:async mail=>mailbox.push(mail) });
const admin=request.agent(app), customer=request.agent(app), other=request.agent(app);
const post=(agent,url,body)=>agent.post(url).set('X-AG-Request','1').send(body);
const password='A carefully chosen test password 42';
const code=()=>mailbox.at(-1).text.match(/code is (\d{6})/)[1];
const quote={customer:'Party Customer',email:'customer@example.com',phone:'082 123 4567',validUntil:'2027-12-01',status:'draft',notes:'Collection at 10am',items:[{description:'Cups',quantity:3,unitPrice:'12.35'},{description:'Plates',quantity:2,unitPrice:'9.99'}],discount:'5.00',taxRate:'15'};
let saved;
before(async()=>{
  const setupCode=fs.readFileSync(path.join(dataDir,'setup-code.txt'),'utf8');
  await post(admin,'/api/auth/setup',{setupCode,email:'admin@example.com',name:'Admin',password}).expect(200);
  await post(admin,'/api/auth/login',{email:'admin@example.com',password}).expect(200);
  await post(admin,'/api/auth/verify',{code:code()}).expect(200);
  await post(customer,'/api/auth/register',{name:'Customer',email:'customer@example.com',password}).expect(200);
  await post(customer,'/api/auth/verify',{code:code()}).expect(200);
  await post(other,'/api/auth/register',{name:'Other',email:'other@example.com',password,role:'admin'}).expect(200);
  await post(other,'/api/auth/verify',{code:code()}).expect(200);
});
after(()=>{app.locals.db.close();assert(dataDir.startsWith(path.join(os.tmpdir(),'ag-balloons-test-')));fs.rmSync(dataDir,{recursive:true,force:true});});
test('setup is single use and designated administrator only',async()=>{
  assert(!fs.existsSync(path.join(dataDir,'setup-code.txt')));
  await post(request(app),'/api/auth/setup',{email:'admin@example.com',password,setupCode:'wrong'}).expect(403);
  const row=app.locals.db.prepare('SELECT * FROM users WHERE email=?').get('admin@example.com');
  assert(!row.password.includes(password));assert.match(row.password,/^[a-f0-9]+:[a-f0-9]+$/);
});
test('password alone is insufficient; email code expires, limits attempts and is single use',async()=>{
  const pending=request.agent(app);
  await post(pending,'/api/auth/login',{email:'admin@example.com',password}).expect(200);
  const valid=code();
  await pending.get('/api/admin/products').expect(401);
  await post(pending,'/api/auth/verify',{code:'000000'}).expect(401);
  await post(pending,'/api/auth/verify',{code:valid}).expect(200);
  await post(pending,'/api/auth/verify',{code:valid}).expect(401);
  const cookies=(await pending.get('/api/auth/status')).headers;
  const rows=app.locals.db.prepare('SELECT token FROM sessions').all();
  assert(rows.every(r=>/^[a-f0-9]{64}$/.test(r.token)));
  await post(pending,'/api/auth/login',{email:'other@example.com',password}).expect(200);
  for(let i=0;i<5;i++)await post(pending,'/api/auth/verify',{code:'000000'}).expect(401);
  await post(pending,'/api/auth/verify',{code:code()}).expect(401);
  await post(pending,'/api/auth/login',{email:'other@example.com',password}).expect(200);
  app.locals.db.prepare('UPDATE challenges SET expires=0').run();
  await post(pending,'/api/auth/verify',{code:code()}).expect(401);
});
test('anonymous and customer callers cannot perform administrator operations',async()=>{
  await request(app).get('/admin.html').expect(302);
  await customer.get('/admin.html').expect(403);
  for(const url of ['/api/admin/products','/api/admin/health','/api/admin/quotes/1/history'])await customer.get(url).expect(403);
  await post(customer,'/api/admin/products',{}).expect(403);
  await post(customer,'/api/admin/quotes',quote).expect(403);
  assert.equal((await other.get('/api/auth/status')).body.user.role,'customer');
});
test('CSRF defenses reject cross-origin and missing custom request header',async()=>{
  await admin.post('/api/admin/quotes').send(quote).expect(403);
  await admin.post('/api/admin/quotes').set('X-AG-Request','1').set('Origin','https://evil.example').send(quote).expect(403);
});
test('quote totals use cents, preserve revisions and isolate customer data',async()=>{
  saved=(await post(admin,'/api/admin/quotes',quote).expect(200)).body;
  assert.equal(saved.subtotalCents,5703);assert.equal(saved.taxCents,780);assert.equal(saved.totalCents,5983);
  assert.match(saved.number,/^AG-\d{4}-\d{5}$/);
  await customer.get('/api/quotes/'+saved.id).expect(404);
  saved=(await post(admin,'/api/admin/quotes',{...quote,id:saved.id,revision:saved.revision,status:'sent'}).expect(200)).body;
  assert.equal((await customer.get('/api/quotes')).body.length,1);
  await other.get('/api/quotes/'+saved.id).expect(404);
  await customer.get('/api/quotes/'+saved.id).expect(200);
  await post(admin,'/api/admin/quotes',{...quote,id:saved.id,revision:1}).expect(409);
  await post(admin,'/api/admin/quotes',{...quote,id:saved.id,revision:saved.revision,email:'other@example.com'}).expect(400);
  const history=(await admin.get(`/api/admin/quotes/${saved.id}/history`).expect(200)).body;
  assert.equal(history.length,2);assert.equal(history[1].document.status,'draft');assert.equal(history[0].document.totalCents,5983);
  await post(admin,`/api/admin/quotes/${saved.id}/email`,{}).expect(200);
  assert(mailbox.at(-1).text.includes(saved.number));
});
