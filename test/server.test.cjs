test('password reset is single use, revokes sessions and still requires email code',async()=>{
  await post(other,'/api/auth/forgot',{email:'other@example.com'}).expect(200);
  const token=mailbox.at(-1).text.match(/reset=([a-f0-9]+)/)[1];
  const nextPassword='Changed secure password 123456';
  await post(other,'/api/auth/reset',{token,password:nextPassword}).expect(200);
  assert.equal((await other.get('/api/auth/status')).body.user,null);
  await post(other,'/api/auth/reset',{token,password:nextPassword}).expect(400);
  await post(other,'/api/auth/login',{email:'other@example.com',password:nextPassword}).expect(200);
  await other.get('/api/quotes').expect(401);
});
