const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const sharp = require('sharp');
const { createApp } = require('../server.cjs');

(async()=>{
  const dataDir=fs.mkdtempSync(path.join(os.tmpdir(),'ag-balloons-browser-'));
  const mailbox=[], origin='http://127.0.0.1:8407';
  const app=createApp({dataDir,test:true,origin,adminEmail:'admin@example.com',sendMail:async mail=>mailbox.push(mail)});
  const server=await new Promise(resolve=>{const s=app.listen(8407,'127.0.0.1',()=>resolve(s));});
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const errors=[];
  const context=await browser.newContext({viewport:{width:1440,height:1100}});
  const page=await context.newPage();page.setDefaultTimeout(12000);page.on('pageerror',error=>errors.push(error.message));
  const out=path.join(__dirname,'../test-results');fs.mkdirSync(out,{recursive:true});
  const password='A strong browser test password 987';
  try{
    const setup=await page.request.post(origin+'/api/auth/setup',{headers:{'X-AG-Request':'1'},data:{email:'admin@example.com',name:'Test Administrator',password,setupCode:fs.readFileSync(path.join(dataDir,'setup-code.txt'),'utf8')}});
    assert.equal(setup.status(),200);
    await page.goto(origin+'/');
    assert(await page.getByRole('link',{name:'Sign in',exact:true}).isVisible());
    assert(!(await page.locator('#admin-link').isVisible()));
    await page.getByRole('link',{name:'Sign in',exact:true}).click();
    await page.getByLabel('Email address',{exact:true}).fill('admin@example.com');
    await page.getByLabel('Password',{exact:true}).fill(password);
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await page.getByRole('heading',{name:'Check your inbox.'}).waitFor();
    const otp=mailbox.at(-1).text.match(/code is (\d{6})/)[1];
    await page.getByLabel('Email verification code').fill(otp);
    await page.getByRole('button',{name:'Verify & continue'}).click();
    await page.getByRole('heading',{name:'A little business magic.'}).waitFor();
    await page.screenshot({path:path.join(out,'dashboard-desktop.png'),fullPage:true});
    await page.getByRole('link',{name:'+ Create quote',exact:true}).click();
    await page.getByLabel('Customer name',{exact:true}).fill('Browser Customer');
    await page.getByLabel('Customer email',{exact:true}).fill('customer@example.com');
    await page.getByLabel('Item description',{exact:true}).fill('Partyware package');
    await page.getByLabel('Quantity',{exact:true}).fill('2');
    await page.getByLabel('Unit price in rand').fill('250.50');
    await page.locator('select[name="status"]').selectOption('sent');
    await page.getByRole('button',{name:'Save quote',exact:true}).click();
    await page.getByRole('heading',{name:'Quotation',exact:true}).waitFor();
    assert((await page.locator('.grand-total').innerText()).includes('501'));
    await page.getByRole('button',{name:'Revision history'}).click();
    await page.locator('.history-entry').waitFor();
    await page.screenshot({path:path.join(out,'quote-desktop.png'),fullPage:true});
    await page.getByRole('link',{name:'Edit quote',exact:true}).click();
    await page.getByLabel('Unit price in rand').fill('300');
    await page.getByRole('button',{name:'Save quote',exact:true}).click();
    await page.getByRole('heading',{name:'Quotation',exact:true}).waitFor();
    assert((await page.locator('.quote-meta').innerText()).includes('Revision 2'));
    await page.getByRole('button',{name:'Email quote',exact:true}).click();
    await page.getByText('Quote emailed successfully.',{exact:true}).waitFor();
    assert(mailbox.at(-1).text.includes('R600.00'));
    await page.getByRole('link',{name:'Products & pricing'}).click();
    await page.getByRole('heading',{name:'The party collection.'}).waitFor();
    await page.locator('.product-tile').filter({has:page.getByRole('heading',{name:'Paper Cups',exact:true})}).getByRole('link',{name:'Edit product'}).click();
    await page.getByLabel('Price (R)',{exact:true}).fill('25');
    await page.getByLabel('Pack size / unit').fill('Pack of 10');
    const png=await sharp({create:{width:160,height:120,channels:3,background:'#f8bfd9'}}).png().toBuffer();
    await page.getByLabel('Product image',{exact:true}).setInputFiles({name:'cups.png',mimeType:'image/png',buffer:png});
    await page.getByRole('button',{name:'Save product',exact:true}).click();
    await page.getByRole('heading',{name:'The party collection.'}).waitFor();
    await page.screenshot({path:path.join(out,'products-desktop.png'),fullPage:true});
    await page.goto(origin+'/');
    await page.locator('#party-stuff .party-card').filter({has:page.getByRole('heading',{name:'Paper Cups',exact:true})}).getByText('Pack of 10',{exact:true}).waitFor();
    assert(await page.locator('#admin-link').isVisible());
    await page.goto(origin+'/admin.html#quotes');
    await page.getByRole('heading',{name:'Every quote, in one place.'}).waitFor();
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(out,'quotes-mobile.png'),fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await page.getByRole('link',{name:'+ Create quote',exact:true}).click();
    await page.getByLabel('Customer name',{exact:true}).waitFor();
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await page.screenshot({path:path.join(out,'quote-editor-mobile.png'),fullPage:true});
    await page.getByRole('button',{name:'Sign out',exact:true}).click();
    await page.getByRole('heading',{name:'Welcome back.'}).waitFor();
    await page.getByRole('button',{name:'Create an account',exact:true}).click();
    await page.getByLabel('Full name',{exact:true}).fill('Browser Customer');
    await page.getByLabel('Email address',{exact:true}).fill('customer@example.com');
    await page.getByLabel('Password',{exact:true}).fill(password);
    await page.getByRole('button',{name:'Create account',exact:true}).click();
    await page.getByRole('heading',{name:'Check your inbox.'}).waitFor();
    await page.getByLabel('Email verification code').fill(mailbox.at(-1).text.match(/code is (\d{6})/)[1]);
    await page.getByRole('button',{name:'Verify & continue'}).click();
    await page.getByRole('heading',{name:'Your quotes.',exact:true}).waitFor();
    assert.equal(await page.locator('tbody tr').count(),1);
    assert(!(await page.getByRole('link',{name:'Administrator dashboard',exact:true}).isVisible()));
    const forbidden=await page.request.get(origin+'/api/admin/products');assert.equal(forbidden.status(),403);
    await page.getByRole('link',{name:'View',exact:true}).click();
    await page.getByRole('heading',{name:'Quotation',exact:true}).waitFor();
    assert((await page.locator('.grand-total').innerText()).includes('600'));
    await page.screenshot({path:path.join(out,'customer-quote-mobile.png'),fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('Browser checks passed: login + email code, quote creation/revisions/email, image upload, public pricing, mobile layout and customer isolation.');
  }catch(error){await page.screenshot({path:path.join(out,'failure.png'),fullPage:true});console.error('Browser URL:',page.url(),'Page errors:',errors);throw error;}finally{await context.close();await browser.close();await new Promise(resolve=>server.close(resolve));app.locals.db.close();assert(dataDir.startsWith(path.join(os.tmpdir(),'ag-balloons-browser-')));fs.rmSync(dataDir,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
